// @vitest-environment jsdom
import React, { createRef } from 'react'
import { afterEach, expect, it } from 'vitest'
import { cleanup, render, screen } from '@testing-library/react'
import { Input } from './Input'

afterEach(cleanup)

it('enforces required instead of only displaying an asterisk', () => {
  render(<Input label="Nama" required />)
  const input = screen.getByLabelText(/Nama/)
  expect(input.required).toBe(true)
  expect(input.checkValidity()).toBe(false)
})

it('connects field errors and persistent guidance to the input', () => {
  render(<Input label="Sandi" error="Terlalu pendek" helperText="Minimal 6 karakter" aria-describedby="external" />)
  const input = screen.getByLabelText('Sandi')
  expect(input.getAttribute('aria-invalid')).toBe('true')
  const ids = input.getAttribute('aria-describedby').split(' ')
  expect(ids).toContain('external')
  expect(ids).toContain(screen.getByText('Terlalu pendek').id)
  expect(ids).toContain(screen.getByText('Minimal 6 karakter').id)
  expect(screen.getByText('Terlalu pendek').getAttribute('role')).toBe('alert')
})

it('keeps autogenerated IDs stable and distinct across rerenders', () => {
  const view = render(<><Input label="Pertama" /><Input label="Kedua" /></>)
  const firstId = screen.getByLabelText('Pertama').id
  const secondId = screen.getByLabelText('Kedua').id
  view.rerender(<><Input label="Pertama" error="Wajib" /><Input label="Kedua" /></>)
  expect(screen.getByLabelText('Pertama').id).toBe(firstId)
  expect(screen.getByLabelText('Kedua').id).toBe(secondId)
  expect(firstId).not.toBe(secondId)
})

it('forwards constraints and ref, and removes stale error references', () => {
  const ref = createRef()
  const view = render(<Input ref={ref} id="capacity" label="Kapasitas" type="number" min={2} max={50} step={1} error="Wajib" />)
  expect(ref.current).toBe(screen.getByLabelText('Kapasitas'))
  expect(ref.current.min).toBe('2')
  expect(ref.current.max).toBe('50')
  view.rerender(<Input ref={ref} id="capacity" label="Kapasitas" helperText="2–50 orang" />)
  expect(ref.current.getAttribute('aria-invalid')).not.toBe('true')
  expect(ref.current.getAttribute('aria-describedby')).toBe(screen.getByText('2–50 orang').id)
  expect(screen.queryByText('Wajib')).toBeNull()
})
